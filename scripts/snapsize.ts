import { World } from '../src/sim/world';
import { templateDesigns } from '../src/sim/presets/designs';
import { snapshot, snapshotToJSON } from '../src/sim/serialize';
const w = new World({ seed: 31, params: { maxPopulation: 800, feedRate: 0.006, lithFeedRate: 0.003 } });
for (const d of templateDesigns()) w.inoculate(d, 70, w.env.cx, w.env.cy, 500);
for (let i = 0; i < 3000; i++) w.step();
const s = snapshot(w);
let bytes = 0;
const walk = (v: unknown) => { if (ArrayBuffer.isView(v)) bytes += (v as Uint8Array).byteLength; else if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === 'object') Object.values(v).forEach(walk); };
walk(s);
let hist = 0; for (const c of s.cells) hist += (c.hist as Float32Array).byteLength;
console.log('cells', w.cells.length, 'typed bytes', (bytes / 1e6).toFixed(2), 'MB; cell hist', (hist / 1e6).toFixed(2), 'MB; history entries', s.history.length, 'json', (snapshotToJSON(s).length / 1e6).toFixed(2), 'MB');
